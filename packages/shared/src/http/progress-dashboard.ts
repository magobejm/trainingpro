export type ProgressExerciseType = 'strength' | 'cardio' | 'plio' | 'mobility' | 'isometric' | 'sport';
export type ProgressExerciseRef = { exerciseId: string; exerciseType: ProgressExerciseType; name: string };
export type ProgressRoutine = {
  assignmentId: string;
  templateId: string;
  revisionId: string | null;
  version: number;
  name: string;
  from: string;
  to: string | null;
  active: boolean;
  cycleDays: number;
  frequency: number;
  objectives: string[];
};
export type ProgressRoutineCatalog = { routines: ProgressRoutine[]; historyFrom: string | null };
export type ProgressAuditSet = {
  sessionId: string;
  sessionDate: string;
  sessionTitle: string;
  incomplete: boolean;
  setIndex: number;
  reps: number | null;
  weightKg: number | null;
  rpe: number | null;
  rir: number | null;
  durationSeconds: number | null;
  distanceMeters: number | null;
  heartRate: number | null;
  fcMaxPercent: number | null;
  fcReservePercent: number | null;
  restSeconds: number | null;
  rom: string | null;
  tonnage: number | null;
  inol: number | null;
};
export type ProgressDailyPoint = {
  distanceHeaders?: Array<{ sessionId: string; distanceMeters: number }>;
  date: string;
  sessionCount: number;
  sets: number;
  totalReps: number | null;
  tonnage: number | null;
  avgRpe: number | null;
  e1rm: number | null;
  maxWeightKg: number | null;
  inol: number | null;
  totalDurationSeconds: number | null;
  distanceMeters: number | null;
  avgHeartRate: number | null;
  avgPaceMinKm: number | null;
  fcMaxPercent: number | null;
  fcReservePercent: number | null;
  effortIndex: number | null;
  efficiency: number | null;
  plioEffort: number | null;
  audit: ProgressAuditSet[];
};
export type ProgressExerciseDaily = {
  exercise: ProgressExerciseRef;
  from: string;
  to: string;
  points: ProgressDailyPoint[];
  kpis: { sessionCount: number; recordE1rm: number | null; maxWeightKg: number | null };
};
export type ProgressRoutineSession = {
  id: string;
  date: string;
  title: string;
  dayIndex: number | null;
  incomplete: boolean;
  tonnage: number | null;
  rpe: number | null;
  durationSeconds: number | null;
  trainingLoad: number | null;
  inol: number | null;
  effortIndex: number | null;
  efficiency: number | null;
};
export type ProgressRoutineCycle = {
  index: number;
  from: string;
  to: string;
  sessions: ProgressRoutineSession[];
  tonnage: number | null;
  avgRpe: number | null;
  trainingLoad: number | null;
  adherence: { done: number; planned: number; percent: number | null };
};
export type ProgressRoutineDetail = {
  routine: ProgressRoutine;
  days: { dayIndex: number; title: string; exercises: ProgressExerciseRef[] }[];
  exercises: ProgressExerciseRef[];
  cycles: ProgressRoutineCycle[];
};
